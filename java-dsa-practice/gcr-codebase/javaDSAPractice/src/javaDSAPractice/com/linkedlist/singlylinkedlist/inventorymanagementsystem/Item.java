class Item {
 int itemId;
 String itemName;
 int quantity;
 double price;

 // Constructor to initialize item details
 Item(int itemId, String itemName, int quantity, double price) {
     this.itemId = itemId;
     this.itemName = itemName;
     this.quantity = quantity;
     this.price = price;
 }
}

